"""The media server (MediaMTX) behind Visionary live video.

    camera RTSP ──pull──▶ MediaMTX path cam/<camera>/<main|sub> ──▶ WebRTC (WHEP) / HLS to browsers and phones
    gateway    ──push──▶ MediaMTX path gw/<gateway>/<camera>/<role>          ──▶ recording (fMP4) + playback API
                                                        └──▶ rtsp://127.0.0.1 for the live AI workers

Security: MediaMTX asks Visionary (POST /api/media/auth) before every read, publish or playback:
  * browsers present a short-lived stream token (JWT, one camera path, 5 minutes), never a camera password
  * gateways publish only under gw/<their id>/ with their own secret
  * the backend's AI workers use an internal credential derived from SECRET_KEY
Camera passwords are only sent to MediaMTX's local API (127.0.0.1) as part of the pull source URL.
"""

from __future__ import annotations

import asyncio
import hashlib
import hmac
import logging
import subprocess
import uuid
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any
from urllib.parse import quote

import httpx
import jwt

from app.cameras.credentials import redact
from app.core.config import Settings, get_settings

logger = logging.getLogger(__name__)
INTERNAL_USER = "visionary-internal"
STREAM_TOKEN_TTL = timedelta(minutes=5)
_process: subprocess.Popen[bytes] | None = None


def internal_password(settings: Settings | None = None) -> str:
    s = settings or get_settings()
    return hmac.new(s.secret_key.get_secret_value().encode(), b"media-internal", hashlib.sha256).hexdigest()[:32]


def camera_path(source_id: uuid.UUID, role: str = "main") -> str:
    return f"cam/{source_id.hex}/{role}"


def gateway_path(gateway_id: uuid.UUID, source_id: uuid.UUID, role: str = "main") -> str:
    return f"gw/{gateway_id.hex}/{source_id.hex}/{role}"


def internal_rtsp_url(path: str, settings: Settings | None = None) -> str:
    s = settings or get_settings()
    return f"rtsp://{INTERNAL_USER}:{internal_password(s)}@127.0.0.1:{s.media_rtsp_port}/{path}"


# -------------------------------------------------------------------------------- stream tokens
def stream_token(user_id: uuid.UUID, path_prefix: str, actions: tuple[str, ...] = ("read",), ttl: timedelta = STREAM_TOKEN_TTL) -> str:
    s = get_settings()
    now = datetime.now(UTC)
    payload = {"typ": "stream", "sub": str(user_id), "path": path_prefix, "act": list(actions), "iat": now, "exp": now + ttl}
    return jwt.encode(payload, s.secret_key.get_secret_value(), algorithm="HS256")


def check_stream_token(token: str, path: str, action: str) -> str | None:
    """User id if the token allows `action` on `path`, else None."""
    try:
        payload = jwt.decode(token, get_settings().secret_key.get_secret_value(), algorithms=["HS256"])
    except jwt.PyJWTError:
        return None
    if payload.get("typ") != "stream" or action not in payload.get("act", []):
        return None
    prefix = payload.get("path", "")
    if not prefix or not (path == prefix or path.startswith(prefix.rstrip("/") + "/")):
        return None
    return payload.get("sub")


